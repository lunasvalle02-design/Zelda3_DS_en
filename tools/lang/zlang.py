"""Zelda3 DS language toolkit.

Shared helpers used by tools/lang/build_assets.py:
  * reading lang/<code>/language.ini
  * generating the dialogue font for a language (US font + extra glyphs)
  * wrapping, validating and encoding the translated dialogue

The US font (font.png) and the US dialogue (dialogue.txt) are extracted from
your ROM by restool.py; nothing copyrighted lives in this repository.
"""
import configparser
import os
import re

# --------------------------------------------------------------------------
# Text box geometry (see VWF_RenderSingle in messaging.c): every line is a
# 0x150-byte buffer = 21 tiles = 168 pixels.
LINE_WIDTH = 168
# Width budgeted for [Name] (player name, up to 6 characters).
NAME_WIDTH = 36
# Width of a [Number xx] digit.
NUMBER_WIDTH = 7
# Index of the first extra glyph. 0-94 is the US alphabet, 95-98 are glyphs
# that only exist in the US font (kept untouched), 99-126 are free.
FIRST_EXTRA_GLYPH = 99
MAX_GLYPHS = 127  # bytes >= 0x7f are commands in the encoding we use

# Commands that only lay out text (they are regenerated by the auto-wrapper).
LAYOUT_CMDS = {'1', '2', '3', 'Scroll', 'Waitkey'}

TOKEN_RE = re.compile(r'\[[^\]]*\]|.', re.S)


def tokenize(s):
  return TOKEN_RE.findall(s)


def cmd_name(tok):
  """'[Speed 02]' -> 'Speed', '[2]' -> '2', 'a' -> None"""
  if len(tok) > 2 and tok[0] == '[' and tok[-1] == ']':
    return tok[1:-1].split(' ', 1)[0]
  return None


