def read_dialogue(path):
  """Reads 'N: text' lines. Returns {N: text}."""
  msgs = {}
  with open(path, encoding='utf-8') as f:
    for ln, line in enumerate(f, 1):
      line = line.rstrip('\r\n')
      if not line.strip() or line.lstrip().startswith('#'):
        continue
      m = re.match(r'\s*(\d+):\s?(.*)$', line)
      if not m:
        raise ValueError(f'{path}:{ln}: expected "<number>: <text>"')
      n = int(m.group(1))
      if n in msgs:
        raise ValueError(f'{path}:{ln}: message {n} defined twice')
      msgs[n] = m.group(2)
  return msgs


def token_width(tok, widths):
  if tok in widths:
    return widths[tok]
  c = cmd_name(tok)
  if c == 'Name':
    return NAME_WIDTH
  if c == 'Number':
    return NUMBER_WIDTH
  return 0


def is_manual(text):
  return any(cmd_name(t) in ('1', '2', '3', 'Scroll') for t in tokenize(text))


def wrap(text, widths):
  """Auto-layout for messages written without [2]/[3]/[Scroll]:
  words are wrapped to LINE_WIDTH, the box shows three lines and then waits
  for a key every three new lines, exactly like the original script.
    [Waitkey]  ends the line and waits for a key before the next one.
    [/]        ends the line. A line that starts with spaces right after [/]
               or [Waitkey] is kept exactly as written ("[/]    > Yes").
  """
  toks = tokenize(text)
  # leading commands stay in front of the first line
  prefix = []
  while toks and cmd_name(toks[0]) is not None and toks[0] not in widths \
      and cmd_name(toks[0]) not in ('Name', 'Waitkey', 'Number', '/'):
    prefix.append(toks.pop(0))
  lines, cur, cur_w = [], [], 0
  forced = set()  # indices of lines followed by a key wait
  word, word_w = [], 0
  verbatim = False

  def flush_word():
    nonlocal cur, cur_w, word, word_w
    if not word:
      return
    space = widths[' '] if cur else 0
    if cur and cur_w + space + word_w > LINE_WIDTH:
      lines.append(cur)
      cur, cur_w, space = [], 0, 0
    if space:
      cur.append(' ')
    cur.extend(word)
    cur_w += space + word_w
    word, word_w = [], 0

  verbatim_lines = set()

  def end_line():
    nonlocal cur, cur_w, verbatim
    flush_word()
    if verbatim:
      verbatim_lines.add(len(lines))
    lines.append(cur)
    cur, cur_w, verbatim = [], 0, False

  i = 0
  while i < len(toks):
    t = toks[i]
    i += 1
    if verbatim and t not in ('[/]', '[Waitkey]'):
      cur.append(t)
    elif t == '[/]':
      end_line()
      verbatim = i < len(toks) and toks[i] == ' '
    elif t == '[Waitkey]':
      end_line()
      forced.add(len(lines) - 1)
      verbatim = i < len(toks) and toks[i] == ' '
    elif t == ' ':
      flush_word()
    else:
      word.append(t)
      word_w += token_width(t, widths)
  flush_word()
  if cur or not lines:
    if verbatim:
      verbatim_lines.add(len(lines))
    lines.append(cur)
  # A question followed by two choice lines must be shown together: wait for
  # a key before the question so the three of them fill the box.
  n = len(lines)
  if n > 3 and {n - 1, n - 2} <= verbatim_lines and (n - 3) not in verbatim_lines:
    forced.add(n - 4)

  out = ''.join(prefix)
  filled = 0  # rows of the (initially empty) box already used
  since = 0   # lines shown since the last key wait
  for i, line in enumerate(lines):
    s = ''.join(line)
    wait = (i - 1) in forced
    if i == 0:
      out += s
    elif filled < 3:
      out += ('[Waitkey]' if wait else '') + ('[2]' if filled == 1 else '[3]') + s
      if wait:
        since = 0
    elif wait or since >= 3:
      out += '[Waitkey][Scroll]' + s
      since = 0
    else:
      out += '[Scroll]' + s
    filled = min(filled + 1, 3)
    since += 1
  return out


def check_message(n, text, us_text, widths, alphabet_set):
  """Returns a list of problems (strings) for one message."""
  problems = []
  toks = tokenize(text)
  for t in toks:
    if t in alphabet_set:
      continue
    c = cmd_name(t)
    if c is None:
      problems.append(f'character {t!r} is not in the font')
  # line widths
  cur = 0
  for t in toks + ['[Scroll]']:
    c = cmd_name(t)
    if c in ('1', '2', '3', 'Scroll'):
      if cur > LINE_WIDTH:
        problems.append(f'line too wide ({cur}px > {LINE_WIDTH}px)')
      cur = 0
    else:
      cur += token_width(t, widths)
  # functional commands must match the original message
  if us_text is not None:
    def functional(s):
      return sorted(t for t in tokenize(s) if cmd_name(t) not in (None, *LAYOUT_CMDS)
                    and t not in alphabet_set)
    a, b = functional(us_text), functional(text)
    if a != b:
      problems.append(f'commands differ from the original: {a} vs {b}')
  return problems
