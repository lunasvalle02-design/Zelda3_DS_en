# language.ini

class LanguageDef:
  def __init__(self, folder):
    self.folder = folder
    cp = configparser.ConfigParser(delimiters=('=',), comment_prefixes=('#', ';'),
                                   inline_comment_prefixes=None, interpolation=None)
    cp.optionxform = str  # keep case: 'Á' and 'á' are different keys
    with open(os.path.join(folder, 'language.ini'), encoding='utf-8') as f:
      cp.read_file(f)
    self.code = cp.get('language', 'code').strip()
    self.name = cp.get('language', 'name', fallback=self.code.upper()).strip()
    if not re.fullmatch(r'[a-z][a-z0-9_-]{0,15}', self.code) or self.code == 'us':
      raise ValueError(f'{folder}: invalid language code {self.code!r}')
    self.glyphs = []  # (char, base, op)
    if cp.has_section('glyphs'):
      for ch, spec in cp.items('glyphs'):
        parts = spec.split()
        if len(ch) != 1 or len(parts) != 2 or len(parts[0]) != 1:
          raise ValueError(f'{folder}: bad glyph line {ch} = {spec}')
        self.glyphs.append((ch, parts[0], parts[1]))
    self.dialogue_path = os.path.join(folder, 'dialogue.txt')
    self.strings_path = os.path.join(folder, 'strings.ini')

  def alphabet(self, us_alphabet):
    """US alphabet, 4 reserved slots, then this language's extra glyphs."""
    a = list(us_alphabet)
    while len(a) < FIRST_EXTRA_GLYPH:
      a.append('[Reserved%d]' % len(a))
    for ch, _, _ in self.glyphs:
      if ch in a:
        raise ValueError(f'{self.code}: glyph {ch!r} already exists in the US font')
      a.append(ch)
    if len(a) > MAX_GLYPHS:
      raise ValueError(f'{self.code}: too many glyphs ({len(a)} > {MAX_GLYPHS})')
    return a


def find_languages(lang_root, wanted=None):
  langs = []
  if not os.path.isdir(lang_root):
    return langs
  for name in sorted(os.listdir(lang_root)):
    folder = os.path.join(lang_root, name)
    if os.path.isfile(os.path.join(folder, 'language.ini')):
      ld = LanguageDef(folder)
      if wanted is None or ld.code in wanted:
        langs.append(ld)
  return langs


# --------------------------------------------------------------------------
# Font PNG (layout written by sprite_sheets.decode_font): 8 rows of 16
# characters; each character row is 17 pixels high: one marker row (pixel 255
# at x = width - 1) followed by 16 rows of 2bpp pixels stored as 96 + value.

FONT_W = 143
PAL_BASE = 96
MARKER = 255


class Font:
  def __init__(self, path):
    from PIL import Image
    self.image = Image.open(path)
    self.data = bytearray(self.image.tobytes())

  @staticmethod
  def _pos(c, r):
    return (c // 16 * 17 + 1 + r) * FONT_W + (c % 16) * 9

  @staticmethod
  def _marker(c):
    return (c // 16 * 17) * FONT_W + (c % 16) * 9

  def glyph(self, c):
    return [[(self.data[self._pos(c, r) + x] - PAL_BASE) & 3 for x in range(8)] for r in range(16)]

  def width(self, c):
    m = self._marker(c)
    for i in range(8):
      if self.data[m + i] == MARKER:
        return i + 1
    return 8

  def set_glyph(self, c, g, width):
    for r in range(16):
      for x in range(8):
        self.data[self._pos(c, r) + x] = PAL_BASE + g[r][x]
    m = self._marker(c)
    for i in range(8):
      self.data[m + i] = 0
    self.data[m + width - 1] = MARKER

  def save(self, path):
    from PIL import Image
    im = Image.frombytes('P', self.image.size, bytes(self.data))
    im.putpalette(self.image.getpalette())
    im.save(path)


# Fill pixels of each diacritic, as (row, column offset from the glyph centre).
_ACCENTS = {
  'acute':      [(0, 1), (1, 0)],
  'grave':      [(0, 0), (1, 1)],
  'circumflex': [(1, -1), (0, 0), (0, 1), (1, 2)],
  'tilde':      [(1, -1), (0, 0), (1, 1), (0, 2)],
  'diaeresis':  [(0, -1), (0, 2)],
}


def _rows_used(g):
  return [r for r in range(16) if any(g[r])]


def _fill_cols(g):
  cols = [x for r in range(16) for x in range(8) if g[r][x] == 2]
  return min(cols), max(cols)


def _squash(g, n):
  """Shorten a glyph by n rows (dropping repeated rows from the middle) and
  move it down so the baseline stays where it was."""
  g = [row[:] for row in g]
  used = _rows_used(g)
  top, bottom = used[0], used[-1]
  for _ in range(n):
    mid = (top + bottom) / 2
    dups = [r for r in range(top + 2, bottom - 1) if g[r] == g[r - 1]]
    if dups:
      r = min(dups, key=lambda r: abs(r - mid))
    else:
      r = int(mid)
    del g[r]
    g.insert(0, [0] * 8)
    top += 1
  return g


def _outline(g, fills, width):
  for (r, x) in fills:
    for dr in (-1, 0, 1):
      for dx in (-1, 0, 1):
        rr, xx = r + dr, x + dx
        if 0 <= rr < 16 and 0 <= xx < width and g[rr][xx] == 0:
          g[rr][xx] = 1
  for (r, x) in fills:
    if 0 <= r < 16 and 0 <= x < 8:
      g[r][x] = 2


def make_glyph(font, base_index, op):
  g = font.glyph(base_index)
  width = font.width(base_index)
  if op == 'flip':
    return [g[15 - r][:] for r in range(16)], width
  if op == 'rotate':
    out = [[0] * 8 for _ in range(16)]
    for r in range(16):
      for x in range(width):
        out[15 - r][width - 1 - x] = g[r][x]
    return out, width
  if op == 'cedilla':
    l, r = _fill_cols(g)
    cx = (l + r) // 2
    bottom = _rows_used(g)[-1]
    fills = [(bottom, cx), (bottom + 1, cx + 1)]
    g = [row[:] for row in g]
    _outline(g, [f for f in fills if f[0] < 16], width)
    return g, width
  if op not in _ACCENTS:
    raise ValueError(f'unknown glyph operation {op!r}')
  shape = _ACCENTS[op]
  height = max(r for r, _ in shape) + 1
  # A dotted i/j: drop the dot (everything above the stem).
  rows = _rows_used(g)
  if base_index in (34, 35):  # 'i', 'j'
    g = [row[:] if r >= 4 else [0] * 8 for r, row in enumerate(g)]
    rows = _rows_used(g)
  top = rows[0]
  # The accent needs `height` fill rows plus one row of outline between it
  # and the letter: squash tall letters (capitals) to make room.
  need = height + 1
  if top < need:
    g = _squash(g, need - top)
    top = need
  l, r = _fill_cols(g)
  cx = (l + r) // 2
  fills = [(top - 1 - height + dr, cx + dx) for dr, dx in shape]
  max_col = max(x for _, x in fills) + 1
  width = max(width, min(8, max_col + 1))
  g = [row[:] for row in g]
  _outline(g, fills, width)
  return g, width


def build_font(us_font_png, out_png, lang, us_alphabet):
  font = Font(us_font_png)
  alphabet = lang.alphabet(us_alphabet)
  index = {ch: i for i, ch in enumerate(us_alphabet)}
  widths = {}
  for i, ch in enumerate(alphabet):
    if i < len(us_alphabet):
      widths[ch] = font.width(i)
  for ch, base, op in lang.glyphs:
    if base not in index:
      raise ValueError(f'{lang.code}: base character {base!r} for {ch!r} is not in the US font')
    g, w = make_glyph(font, index[base], op)
    font.set_glyph(alphabet.index(ch), g, w)
    widths[ch] = w
  font.save(out_png)
  return alphabet, widths


